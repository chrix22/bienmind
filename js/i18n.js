  t(lang, key) {
    return (this.translations[lang] && this.translations[lang][key] !== undefined)
      ? this.translations[lang][key]
      : (this.translations.en[key] !== undefined ? this.translations.en[key] : key);
  },

  apply(lang) {
    // textContent
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(lang, el.dataset.i18n);
    });
    // innerHTML (for elements containing <br>, <em>, <strong>)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = this.t(lang, el.dataset.i18nHtml);
    });
    // placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(lang, el.dataset.i18nPlaceholder);
    });
    // form submit button (only if not in sent-state)
    const submitBtn = document.querySelector('.contact__form [type="submit"]');
    if (submitBtn && !submitBtn.disabled) {
      submitBtn.textContent = this.t(lang, 'contact.form.submit');
    }
    // html lang attribute
    document.documentElement.lang = lang;
  },
